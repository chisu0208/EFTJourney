"""Map metadata (tarkov.dev transforms, SVG urls, extracts) keyed by the game's location ids.

eftjourney/data/maps.json is generated by scripts/update_maps.py. Each entry lists
every location id the game uses for that map in "ids" (lowercase), e.g. Factory
is both factory4_day and factory4_night.
"""
from __future__ import annotations

import json
from pathlib import Path

MAPS_FILE = Path(__file__).resolve().parent / "data" / "maps.json"


def load_maps(path: Path = MAPS_FILE) -> dict:
    try:
        doc = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {"maps": []}
    return doc if isinstance(doc, dict) and isinstance(doc.get("maps"), list) else {"maps": []}


def entry_for(maps: dict, location_id: str | None) -> dict | None:
    key = (location_id or "").strip().lower()
    if not key:
        return None
    return next((m for m in maps.get("maps", []) if key in m.get("ids", [])), None)


def canonical_id(maps: dict, location_id: str | None) -> str | None:
    """'Factory4_Night' -> 'factory4_day' style canonical id (first id of the entry)."""
    if not location_id:
        return None
    entry = entry_for(maps, location_id)
    return entry["ids"][0] if entry else location_id.strip().lower()


def contains(entry: dict, x: float, z: float, pad: float = 0.0) -> bool:
    """Is game point (x, z) inside the map's bounds [[x1, z1], [x2, z2]], grown by pad metres?"""
    (x1, z1), (x2, z2) = entry["bounds"]
    return min(x1, x2) - pad <= x <= max(x1, x2) + pad and min(z1, z2) - pad <= z <= max(z1, z2) + pad


def guess_map(maps: dict, track: list[dict]) -> str | None:
    """Best-effort map guess for screenshots without a matching log raid.

    Many maps share coordinate ranges, so this only answers when exactly one
    map's bounds contain every sampled point; otherwise the user picks the map.
    """
    if not track:
        return None
    hits = [m for m in maps.get("maps", []) if m.get("bounds") and all(contains(m, p["x"], p["z"]) for p in track)]
    return hits[0]["ids"][0] if len(hits) == 1 else None
