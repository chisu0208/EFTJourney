"""On-disk raid store.

data/raids/<id>.json        generated by the builder (overwritten on every scan)
data/raids/<id>.edits.json  what the user typed in the viewer (never overwritten by scans)

The viewer always receives the two merged, so rebuilding raids from new
screenshots never loses hand-entered kills or the raid outcome.
"""
from __future__ import annotations

import json
import math
import os
import re
import sys
import tempfile
import time
from pathlib import Path
from typing import Any, Callable

RAID_ID_RE = re.compile(r"^\d{8}-\d{6}-[a-z0-9_]+$")

OUTCOME_STATUSES = ("survived", "killed", "mia", "runthrough", "left", "transit", "unknown")
SIDES = ("", "pmc", "usec", "bear", "scav", "raider", "rogue", "boss", "follower", "cultist", "player_scav", "other")
BODY_PARTS = ("", "head", "thorax", "stomach", "leftarm", "rightarm", "leftleg", "rightleg")

MAX_TEXT = 200
MAX_NOTES = 4000
MAX_KILLS = 500


def _while_in_use(action: Callable[..., Any], *args: Any) -> Any:
    """action(*args), tried again while Windows refuses it with a PermissionError.

    Windows refuses to replace or delete a file while anyone has it open (a request reading
    it, a virus scanner: Python's open() leaves out FILE_SHARE_DELETE); those holds are short.
    """
    attempts = 10
    for attempt in range(1, attempts + 1):
        try:
            return action(*args)
        except PermissionError:
            if attempt == attempts:
                raise
            time.sleep(0.05)


def _atomic_write_json(path: Path, doc: Any) -> None:
    _atomic_write_text(path, json.dumps(doc, ensure_ascii=False, indent=1))


def _atomic_write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=path.name, suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(text)
            # on disk before the rename: a power cut must not leave a zero-filled file behind
            fh.flush()
            os.fsync(fh.fileno())
        _while_in_use(os.replace, tmp, path)  # held by a request reading the old copy, or a virus scanner
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def _delete(path: Path) -> None:
    try:
        _while_in_use(path.unlink)  # the viewer's server may be reading it right now
    except FileNotFoundError:
        pass


def _read_json(path: Path) -> Any | None:
    try:
        # utf-8-sig: a file saved by hand with a BOM (Notepad's "UTF-8 with BOM", PowerShell 5.1) is fine
        with path.open(encoding="utf-8-sig") as fh:
            return json.load(fh)
    except (OSError, ValueError, RecursionError):  # RecursionError: a hand-made file nested deeper than json.load goes
        return None


def _text(value: Any, limit: int = MAX_TEXT) -> str:
    if value is None:
        return ""
    # a lone surrogate ("\ud800" in the JSON) becomes "?": UTF-8 can't carry it, to disk or to the browser
    text = str(value).encode("utf-8", "replace").decode("utf-8")
    # stripped again after the cut, so cleaning clean edits once more changes nothing
    return text.strip()[:limit].rstrip()


def _number(value: Any, lo: float, hi: float) -> float | None:
    if value is None or value == "" or isinstance(value, bool):
        return None
    try:
        num = float(value)
    except (TypeError, ValueError, OverflowError):  # OverflowError: an int too big for a float
        return None
    if not math.isfinite(num):
        return None
    return min(max(num, lo), hi)


def _choice(value: Any, allowed: tuple[str, ...], default: str) -> str:
    text = _text(value).lower().replace(" ", "").replace("-", "")
    return text if text in allowed else default


def _clean_kill(raw: Any, index: int) -> dict | None:
    if not isinstance(raw, dict):
        return None
    t = _number(raw.get("t"), 0, 6 * 3600)
    if t is None:
        return None
    level = _number(raw.get("level"), 0, 200)
    return {
        "id": _text(raw.get("id"), 40) or f"k{index + 1}",
        "t": round(t, 1),
        "name": _text(raw.get("name")),
        "level": int(level) if level is not None else None,
        "side": _choice(raw.get("side"), SIDES, "other" if raw.get("side") else ""),
        "weapon": _text(raw.get("weapon")),
        "bodyPart": _choice(raw.get("bodyPart"), BODY_PARTS, ""),
        "distance": _number(raw.get("distance"), 0, 5000),
        "note": _text(raw.get("note"), 500),
        "source": _choice(raw.get("source"), ("manual", "ocr"), "manual"),
    }


def _clean_kills(raw: Any) -> list[dict]:
    if not isinstance(raw, list):
        return []
    return [k for i, item in enumerate(raw[:MAX_KILLS]) if (k := _clean_kill(item, i))]


def clean_edits(raw: Any) -> dict:
    """Whitelist + coerce user edits so the viewer can't write arbitrary JSON to disk."""
    if not isinstance(raw, dict):
        raise ValueError("edits must be a JSON object")
    out: dict[str, Any] = {}
    if raw.get("map"):
        mapped = _text(raw["map"], 40).lower()
        if re.fullmatch(r"[a-z0-9_]+", mapped):
            out["map"] = mapped
    if "title" in raw:
        out["title"] = _text(raw.get("title"))
    if "notes" in raw:
        out["notes"] = _text(raw.get("notes"), MAX_NOTES)
    if isinstance(raw.get("outcome"), dict):
        o = raw["outcome"]
        out["outcome"] = {
            "status": _choice(o.get("status"), OUTCOME_STATUSES, "unknown"),
            "t": _number(o.get("t"), 0, 6 * 3600),
            "killer": _text(o.get("killer")),
            "killerSide": _choice(o.get("killerSide"), SIDES, ""),
            "weapon": _text(o.get("weapon")),
            "bodyPart": _choice(o.get("bodyPart"), BODY_PARTS, ""),
            "distance": _number(o.get("distance"), 0, 5000),
            "exit": _text(o.get("exit")),
            "source": _choice(o.get("source"), ("manual", "ocr", "log"), "manual"),
        }
    if isinstance(raw.get("kills"), list):
        out["kills"] = sorted(_clean_kills(raw["kills"]), key=lambda k: k["t"])
    return out


def track_distance(track: list[dict]) -> float:
    """Metres walked along the sampled route, top-down (x/z)."""
    total = 0.0
    for a, b in zip(track, track[1:]):
        # floats first: two ints that each fit a float can differ by more than one holds (hypot raised
        # OverflowError); as floats the difference is infinity, which summaries() lists as 0.0
        total += math.hypot(float(b["x"]) - float(a["x"]), float(b["z"]) - float(a["z"]))
    return round(total, 1)


def _finite(value: Any) -> bool:
    """A real number: no bool, NaN or infinity (Python's json reads those), no int too big for a float."""
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        return False
    try:
        return math.isfinite(value)
    except OverflowError:
        return False


def _sendable(doc: Any) -> Any:
    """A stored document as browsers take it: NaN and infinity become None, a lone surrogate "?".

    Python's json reads them from a file edited by hand (NaN, 1e999, "\\ud800"), while
    JSON.parse rejects the first two and UTF-8 can't carry the last. The rest comes back as it was.
    """
    text = json.dumps(doc, ensure_ascii=False).encode("utf-8", "replace")
    return json.loads(text, parse_constant=lambda name: None)


def _placed(item: Any) -> bool:
    """A point the viewer draws: a time and a top-down position, all real numbers (app.js skips the rest)."""
    return isinstance(item, dict) and _finite(item.get("t")) and _finite(item.get("x")) and _finite(item.get("z"))


def _drawable(track: Any) -> list[dict]:
    """The samples of a stored track that the viewer draws (stored files can be edited by hand)."""
    if not isinstance(track, list):
        return []
    # height, heading and in-game time don't place a sample: one that is no number becomes None (unknown)
    return [dict(s, **{key: None for key in ("y", "yaw", "tod") if key in s and not _finite(s[key])})
            for s in track if _placed(s)]


def _stored_outcome(raw: Any) -> dict | None:
    """A raid file's own outcome (the logs' transit): an object, its time one the viewer can place or None."""
    if not isinstance(raw, dict):
        return None
    return dict(raw, t=None) if "t" in raw and not _finite(raw["t"]) else raw


def _str(value: Any, default: str | None = None) -> str | None:
    return value if isinstance(value, str) else default


class RaidStore:
    def __init__(self, root: Path):
        self.root = Path(root)
        self.raids_dir = self.root / "raids"

    def _path(self, raid_id: str, suffix: str) -> Path:
        if not RAID_ID_RE.match(raid_id or ""):
            raise KeyError(raid_id)
        return self.raids_dir / f"{raid_id}{suffix}"

    def raid_file(self, raid_id: str) -> Path:
        return self._path(raid_id, ".json")

    def edits_file(self, raid_id: str) -> Path:
        return self._path(raid_id, ".edits.json")

    def suspect_files(self, raid_id: str) -> str:
        """The files merged() read, for a message that can't tell which of them is at fault: the
        raid file, and its edits file only when there is one."""
        edits = self.edits_file(raid_id)
        return f"{self.raid_file(raid_id)} 또는 {edits}" if edits.exists() else str(self.raid_file(raid_id))

    def list_ids(self) -> list[str]:
        if not self.raids_dir.is_dir():
            return []
        ids = [p.name[:-5] for p in self.raids_dir.glob("*.json") if not p.name.endswith(".edits.json")]
        return sorted((i for i in ids if RAID_ID_RE.match(i)), reverse=True)

    def load_raid(self, raid_id: str) -> dict | None:
        doc = _read_json(self._path(raid_id, ".json"))
        return doc if isinstance(doc, dict) else None  # a damaged or hand-made file: no raid

    def save_raid(self, raid: dict) -> None:
        _atomic_write_json(self._path(raid["id"], ".json"), raid)

    def delete_raid(self, raid_id: str) -> None:
        _delete(self._path(raid_id, ".json"))

    def delete_edits(self, raid_id: str) -> None:
        _delete(self._path(raid_id, ".edits.json"))

    def load_edits(self, raid_id: str) -> dict:
        doc = _read_json(self._path(raid_id, ".edits.json"))
        return doc if isinstance(doc, dict) else {}

    def read_edits(self, raid_id: str) -> dict | None:
        """The edits as stored ({} without a file), or None when the file is there but cannot be
        read (a hand edit gone wrong, held by another program): what the user typed in it must
        then be neither moved nor written over."""
        path = self._path(raid_id, ".edits.json")
        doc = _read_json(path)
        if isinstance(doc, dict):
            return doc
        return None if path.exists() else {}

    def save_edits(self, raid_id: str, raw: Any) -> dict:
        if self.load_raid(raid_id) is None:
            raise KeyError(raid_id)
        edits = clean_edits(raw)
        _atomic_write_json(self._path(raid_id, ".edits.json"), edits)
        return edits

    def merged(self, raid_id: str) -> dict | None:
        raid = self.load_raid(raid_id)
        if raid is None:
            return None
        stored = self.read_edits(raid_id)
        edits = stored or {}
        shown = clean_edits(edits)  # an edits file changed by hand shows only what the viewer could save
        # and a raid file changed by hand (or by another tool) shows only what the viewer can read and
        # draw: every raid the list shows also opens, and its counts are what is drawn
        doc = _sendable(raid)
        doc["id"] = raid_id  # the name it is stored under: what the viewer opens and saves edits to
        doc["detectedMap"] = doc.get("map")
        doc["track"] = _drawable(doc.get("track"))
        doc["kills"] = _clean_kills(doc.get("kills"))  # cleaned as the viewer's are; generated raids have none
        if "logFixes" in doc:
            fixes = doc["logFixes"]
            doc["logFixes"] = [f for f in fixes if _placed(f)] if isinstance(fixes, list) else []
        if "outcome" in doc:
            doc["outcome"] = _stored_outcome(doc["outcome"])
        if "duration" in doc and not _finite(doc["duration"]):
            doc["duration"] = None
        for key in ("map", "title", "notes", "outcome", "kills"):
            if key in shown:
                doc[key] = shown[key]
        doc["edited"] = stored is None or bool(edits)  # any edits file counts, as it does for the scan: an unreadable one too
        return doc

    def summaries(self) -> list[dict]:
        out = []
        for raid_id in self.list_ids():
            try:
                row = self._summary(raid_id)
                if row is None:
                    continue
                # as the server sends it: merged() leaves nothing that fails here, but a row that does is left out
                json.dumps(row, ensure_ascii=False, allow_nan=False).encode("utf-8")
            except Exception:  # last resort: one file must never take the whole list down
                print(f"레이드 목록에서 뺐습니다 (읽을 수 없는 모양): {self.suspect_files(raid_id)}", file=sys.stderr)
                continue
            out.append(row)
        return out

    def _summary(self, raid_id: str) -> dict | None:
        """One list row. Stored files can be edited by hand or by other tools, so every value is checked."""
        doc = self.merged(raid_id)
        if not doc:
            return None
        track = doc["track"]
        outcome = doc.get("outcome") if isinstance(doc.get("outcome"), dict) else {}
        kills, fixes = doc.get("kills"), doc.get("logFixes")
        distance = track_distance(track)
        return {
            "id": raid_id,
            "map": _str(doc.get("map")),
            "mode": _str(doc.get("mode")),
            "title": _str(doc.get("title"), ""),
            "startedAt": _str(doc.get("startedAt")),
            "endedAt": _str(doc.get("endedAt")),
            "duration": doc.get("duration") if _finite(doc.get("duration")) else None,
            "durationApprox": bool(doc.get("durationApprox")),
            "samples": len(track),
            "fixes": len(fixes) if isinstance(fixes, list) else 0,
            "distance": distance if math.isfinite(distance) else 0.0,  # coordinates near the float limit
            "kills": len(kills) if isinstance(kills, list) else 0,
            "outcome": _str(outcome.get("status")) or "unknown",
            "demo": bool(doc.get("demo")),
        }
